#!/usr/bin/env python3
"""
hierarchy.py — recover each class's BASE class (single-inheritance) from the vtables.

A class's vtable slots are owned ONLY by itself and its ANCESTORS (inherited/non-overridden slots still
point at the ancestor that last defined them; siblings never appear). So the immediate base of X is the
ancestor that OWNS slots in X's vtable and has the longest vtable of its own (= closest ancestor). Reads
VTABLES.md (extract_vtables.py output). [Name-prefix matching fails — all CBaseEntity-derived classes
share the same leading virtuals, so it picks a coincidental sibling.]

Needed for the refactor: writing `class CTSKnife : public CTSPhysicObject` faithfully instead of guessing
the base. (Multiple inheritance is rare in the HL SDK and not handled — flagged as ambiguous if seen.)

Outputs:
  reference/coverage/HIERARCHY.md     — class -> base, and the rooted trees
  reference/coverage/hierarchy.tsv    — class<TAB>base

  python3 scripts/coverage/hierarchy.py            # all
  python3 scripts/coverage/hierarchy.py <Class>     # one class's ancestry chain
"""
import os, re, sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VT   = os.path.join(ROOT, "reference", "coverage", "VTABLES.md")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "HIERARCHY.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "hierarchy.tsv")


def load_vtables():
    """{class: [owner_class_per_slot]} from VTABLES.md (slot order = file order; None for unparsed)."""
    vt = defaultdict(list)
    cur = None
    for ln in open(VT, errors="replace"):
        h = re.match(r"^##\s+(\S+)", ln)
        if h:
            cur = h.group(1)
            continue
        if cur:
            m = re.search(r"→\s*([A-Za-z_]\w*)::(~?\w+)\s*\(", ln)
            if m:
                vt[cur].append(m.group(1))      # the OWNER class of this slot
            elif "→" in ln:
                vt[cur].append(None)
    return vt


def base_of(vt):
    """{class: base}: the slot-owning ancestor with the longest vtable (= immediate base)."""
    vlen = {c: len(v) for c, v in vt.items()}
    base = {}
    for c, owners in vt.items():
        cand = {o for o in owners if o and o != c and o in vlen and vlen[o] < vlen[c]}
        if cand:
            base[c] = max(cand, key=lambda o: vlen[o])
    return base


def chain(c, base):
    out = [c]
    seen = {c}
    while c in base and base[c] not in seen:
        c = base[c]; out.append(c); seen.add(c)
    return out


def main():
    vt = load_vtables()
    base = base_of(vt)

    if len(sys.argv) > 1:
        c = sys.argv[1]
        print(" : ".join(f"public {x}" if i else x for i, x in enumerate(chain(c, base))))
        return

    children = defaultdict(list)
    for c, b in base.items():
        children[b].append(c)
    roots = sorted(set(vt) - set(base))

    L = ["# Recovered class hierarchy (base classes from vtable-prefix matching)", "",
         "Generated by `scripts/coverage/hierarchy.py` from VTABLES.md. `class X : public BASE` for the "
         "refactor. Single inheritance assumed (HL SDK norm).", "",
         f"**{len(vt)} classes · {len(base)} with a recovered base · {len(roots)} roots.**", "",
         "## class → base", "", "| class | base |", "|---|---|"]
    tsv = ["Class\tbase"]
    for c in sorted(base):
        L.append(f"| `{c}` | `{base[c]}` |")
        tsv.append(f"{c}\t{base[c]}")

    def tree(node, depth, acc):
        acc.append("  " * depth + f"- {node}")
        for ch in sorted(children.get(node, [])):
            tree(ch, depth + 1, acc)

    L += ["", "## inheritance trees (TS-relevant roots)", ""]
    acc = []
    for r in roots:
        if any(x.startswith(("CTS", "CM61", "CVip", "CBulletManager")) for x in chain_down(r, children)):
            tree(r, 0, acc)
    L += acc

    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {len(base)} class→base relations")


def chain_down(node, children):
    out = [node]
    for ch in children.get(node, []):
        out += chain_down(ch, children)
    return out


if __name__ == "__main__":
    main()
